#!/usr/bin/env python3
"""Run inside the ROS container to regenerate the simulation-only approach overrides."""
# 从 real_sim.yaml 复制任务参数，只改仿真航点接近段与搬运段，写入 grasp-plan.yaml 覆盖文件。
import math
from pathlib import Path
import yaml

root=Path(__file__).resolve().parent.parent
# 用安全 YAML 解析器读取基础任务；overrides 只保存本脚本实际修改的阶段。
source=yaml.safe_load((root/'src/flygripper_planner/flygripper_planner/params/real_sim.yaml').read_text())
overrides={}
for stage in (1,3,5,7):
    # 抓取阶段在原目标前沿航向反方向增加 0.35 米接近点，保留原目标作为末点。
    task=source[f'task_{stage}']; count=task['plan_point_num']
    goal=task[f'plan_point_{count-1}'].copy()
    approach=goal.copy()
    approach['x']-=.35*math.cos(goal['yaw'])
    approach['y']-=.35*math.sin(goal['yaw'])
    task[f'plan_point_{count-1}']=approach
    task[f'plan_point_{count}']=goal
    task.update(plan_point_num=count+1,plan_max_vel=.2,plan_max_acc=.3,plan_tolerance=.008,
                morph_auto=True)
    overrides[f'task_{stage}']=task
    # 对应搬运阶段减速并锁定 yaw，所有相关阶段都设置自动形变。
    carry=source[f'task_{stage+1}']
    carry.update(plan_max_vel=.2,plan_max_acc=.2,plan_max_dyaw=.2,
                 morph_auto=True)
    for i in range(carry['plan_point_num']):
        carry[f'plan_point_{i}']['yaw']=goal['yaw']
    if stage == 1:
        # 易拉罐先垂直抬升两段，离开支撑后再沿后续航点横向搬运。
        points=[carry[f'plan_point_{i}'] for i in range(carry['plan_point_num'])]
        lift1=dict(goal,z=goal['z']+.10)
        lift2=dict(goal,z=goal['z']+.20)
        points=[lift1,lift2]+points
        carry['plan_point_num']=len(points)
        for i,p in enumerate(points): carry[f'plan_point_{i}']=p
    overrides[f'task_{stage+1}']=carry
# 该文件是基础配置的局部覆盖项，不包含的阶段继续使用 real_sim.yaml 原值。
(root/'docker/grasp-plan.yaml').write_text('# Generated by docker/make_grasp_plan.py; simulation overrides only.\n'+yaml.safe_dump(overrides))
